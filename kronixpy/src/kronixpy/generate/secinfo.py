import os, re
from string import Template
from ..utils.errprint import *
from ..common import Namespace, common_main

_INCGUARD_REGEX: re.Pattern[str] = re.compile(r"^.*/include/(.+)$")


def c_incguard(hdr: str) -> str:
    hdr = os.path.realpath(hdr, strict=os.path.ALLOW_MISSING)
    match _INCGUARD_REGEX.match(hdr):
        case None:
            raise ValueError(f"bad file path: {hdr}")
        case matched:
            matched = iter(matched.group(1).upper())
            match next(matched):
                case ch if ch.isalpha():
                    guard = ch
                case ch if ch.isnumeric():
                    guard = "_" + ch
                case ch:
                    guard = "_"
            for ch in matched:
                if ch.isalnum():
                    guard += ch
                else:
                    guard += "_"
            return guard + "_INCLUDED_"


def main(args: Namespace) -> int:
    common_main(args)
    rs_extern_sym = Template(
        """
unsafe extern "C"
{
    pub unsafe static kronix_${symbol}_start: LinkerSym;
    pub unsafe static kronix_${symbol}_end  : LinkerSym;
}
"""
    )

    section_csyms = Template(
        """
// --- SECTIONINFO START: ${section} ---
extern const symbol kronix_${section}_start;
extern const symbol kronix_${section}_end;
static const size_t kronix_${section}_size = (size_t)((uintptr_t)(const void*)kronix_${section}_end - (uintptr_t)(const void*)kronix_${section}_start);
// --- SECTIONINFO END: ${section} ---
"""
    )
    section_rssyms = Template(
        """
unsafe extern "C"
{
    pub unsafe static kronix_${section}_start: LinkerSym;
    pub unsafe static kronix_${section}_end  : LinkerSym;
}
lazy_static! {
    #[allow(non_upper_case_globals)]
    pub static ref kronix_${section}_size: usize = {
        unsafe {
            (kronix_${section}_end   as usize) -
            (kronix_${section}_start as usize)
        }
    };
}
"""
    )
    section_ldsyms = Template(
        """
/* --- SECTIONINFO START: ${section} --- */
ASSERT(LOADADDR(.${section}) == ABSOLUTE(ADDR(.${section})), "Section ${section} is not loaded at the correct address");

. = ALIGN(CONSTANT(MAXPAGESIZE) / 64);
kronix_${section}_start = LOADADDR(.${section});

. = ALIGN(CONSTANT(MAXPAGESIZE) / 64);
kronix_${section}_end = LOADADDR(.${section}) + SIZEOF(.${section});
/* --- SECTIONINFO END: ${section} --- */
"""
    )
    todump_csyms: str = ""
    todump_rssyms: str = ""
    todump_ldsyms: str = ""

    section_count = 0

    for sec in args.sections:
        todump_csyms += section_csyms.substitute(section=sec)
        todump_rssyms += section_rssyms.substitute(section=sec)
        todump_ldsyms += section_ldsyms.substitute(section=sec)
        section_count += 1

    rs_ksyms = rs_extern_sym.substitute(symbol="kernel")
    c_include_guard = (
        c_incguard(args.output_cfile)
        if args.output_cfile is not None
        else "KRONIX_SECTIONINFO_H_INCLUDED_"
    )
    # fmt: off
    todump_csyms  = f"\n// --- SECTIONINFO AUTOGENERATED BY {os.path.realpath(__file__)}, START ---\n" \
                  + f"#if !{c_include_guard}\n"                                                        \
                  + f"#define {c_include_guard} 1\n"                                                   \
                  +  "#include <stddef.h>\n"                                                           \
                  +  "#include <misc/symbol.h>\n"                                                      \
                  +  todump_csyms                                                                      \
                  +  "#endif\n"                                                                        \
                  + f"\n// --- SECTIONINFO AUTOGENERATED BY {os.path.realpath(__file__)}, END ---\n"
    todump_rssyms = f"\n// --- SECTIONINFO AUTOGENERATED BY {os.path.realpath(__file__)}, START ---\n"  \
                  +  "pub mod __linker_symbols\n"                                                       \
                  +  "{\n"                                                                              \
                  +  "    #![allow(dead_code)]\n"                                                       \
                  +  "    #![allow(non_upper_case_globals)]\n"                                          \
                  +  "    use lazy_static::lazy_static;\n"                                              \
                  +  "    use super::super::LinkerSym;\n"                                               \
                  + f"    pub const kronix_section_count: usize = {section_count};\n"                   \
                  +  rs_ksyms.replace('\n', '\n    ', rs_ksyms.count('\n') - 1)                         \
                  +  todump_rssyms.replace('\n', '\n    ', todump_rssyms.count('\n') - 1)               \
                  +  "}\n"                                                                              \
                  + f"\n// --- SECTIONINFO AUTOGENERATED BY {os.path.realpath(__file__)}, END ---\n"
    todump_ldsyms = f"\n/* --- SECTIONINFO AUTOGENERATED BY {os.path.realpath(__file__)}, START --- */\n" \
                  + todump_ldsyms                                                                         \
                  + f"\n/* --- SECTIONINFO AUTOGENERATED BY {os.path.realpath(__file__)}, END --- */\n"
    # fmt: on
    if args.output_cfile is not None:
        _files: str = args.output_cfile
        for filepath in _files.split(","):
            with open(filepath, "w") as f:
                f.write(todump_csyms)
                f.flush()

    if args.output_rsfile is not None:
        _files: str = args.output_rsfile
        for filepath in _files.split(","):
            with open(filepath, "w") as f:
                f.write(todump_rssyms)
                f.flush()

    if args.input_linkerfile is not None:
        with open(args.input_linkerfile, "r") as fr:
            _content = fr.read().replace("!!!__GENSECTION_FILL__!!!", todump_ldsyms)
            _files: str = args.output_linkerfile
            for filepath in _files.split(","):
                with open(filepath, "w") as fw:
                    fw.write(_content)
                    fw.flush()

    return 0
